#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES.md: every production dependency with its license text, as their
// licenses (MIT, BSD, Apache, OFL…) ask when the code is redistributed, e.g. in the Docker image.
// `--check` fails when the committed file is out of date, so CI catches a dependency change.
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const OUT = 'THIRD_PARTY_NOTICES.md';
/** Installed but kept out of everything Ordler ships (see apps/web/src/build/no-elk.ts). */
const NOT_SHIPPED = new Set(['elkjs']);
const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.|-|$)/i;

// Under `pnpm run` the pnpm binary may not be on PATH; npm_execpath points at it.
const pnpm = process.env.npm_execpath?.match(/\.c?js$/)
  ? [process.execPath, [process.env.npm_execpath]]
  : ['pnpm', []];
const byLicense = JSON.parse(
  execFileSync(pnpm[0], [...pnpm[1], 'licenses', 'list', '--prod', '--json'], {
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  }),
);

const packages = [];
for (const [license, list] of Object.entries(byLicense)) {
  for (const pkg of list) {
    if (pkg.name.startsWith('@ordler/') || NOT_SHIPPED.has(pkg.name)) continue;
    pkg.versions.forEach((version, index) => {
      const dir = pkg.paths[index];
      const files =
        dir && existsSync(dir)
          ? readdirSync(dir)
              .filter((f) => LICENSE_FILE.test(f))
              .sort()
          : [];
      const text = files
        .map((f) => readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim())
        .join('\n\n');
      packages.push({ name: pkg.name, version, license, homepage: pkg.homepage ?? '', text });
    });
  }
}
packages.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const fence = (text) => {
  const ticks = '`'.repeat(Math.max(3, ...[...text.matchAll(/`+/g)].map((m) => m[0].length + 1)));
  return `${ticks}text\n${text}\n${ticks}`;
};
const body = packages
  .map((p) =>
    [
      `## ${p.name}@${p.version}`,
      '',
      `License: ${p.license}${p.homepage ? `  \nHomepage: <${p.homepage}>` : ''}`,
      '',
      p.text ? fence(p.text) : '_No license file in the package; see the license named above._',
    ].join('\n'),
  )
  .join('\n\n');

const content = `<!-- Generated by scripts/third-party-notices.mjs; do not edit by hand. -->

# Third-party notices

Ordler is licensed under the GNU AGPL-3.0 (see [LICENSE](LICENSE)). It includes the open source
packages below, used under their own licenses. ${packages.length} packages.

${body}
`;

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== content) {
    console.error(`${OUT} is out of date. Run: pnpm notices`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${packages.length} packages).`);
} else {
  writeFileSync(OUT, content);
  console.log(`Wrote ${OUT} (${packages.length} packages).`);
}
